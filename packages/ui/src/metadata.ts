import type { Metadata } from "next";

export type SiteIdentity = {
  name: string;
  /** Canonical origin, no trailing slash — e.g. https://www.zbestmedia.com */
  origin: string;
  description: string;
};

/**
 * Site-wide metadata defaults for a root layout (Brief §3.3, §7).
 *
 * Deliberately sets NO canonical. A canonical declared in the root layout is
 * inherited by every page that does not override it, so one forgotten page
 * would silently tell search engines it is a duplicate of the homepage. Each
 * page declares its own through `pageMetadata`, and the gate checks every
 * built page carries the right one.
 *
 * The OG image comes from the app's root `opengraph-image.tsx` (file-based
 * metadata), which Next applies to every route that has no image of its own.
 */
export function siteMetadata(site: SiteIdentity): Metadata {
  return {
    metadataBase: new URL(site.origin),
    title: { default: site.name, template: `%s — ${site.name}` },
    description: site.description,
    applicationName: site.name,
    openGraph: {
      type: "website",
      siteName: site.name,
      locale: "en_US",
      title: site.name,
      description: site.description,
    },
    twitter: { card: "summary_large_image" },
  };
}

const DEFAULT_OG_IMAGE = "/opengraph-image";

/**
 * Per-page metadata: canonical, OG url and robots, resolved against the
 * layout's `metadataBase`.
 *
 * `openGraph` is rebuilt in full rather than partially overridden because Next
 * merges metadata shallowly — a page that sets `openGraph: { title }` drops the
 * layout's siteName, type and locale.
 *
 * The image is named explicitly for the same reason: a page-level `openGraph`
 * object replaces the file-based image, even one generated by an
 * opengraph-image.tsx in the page's own segment (checked against this build —
 * the first version of this helper shipped /legal/* with no og:image at all).
 * So a page with its own opengraph-image.tsx must pass that route as `ogImage`;
 * every other page gets the site default.
 */
export function pageMetadata(
  site: SiteIdentity,
  {
    title,
    description = site.description,
    path,
    index = true,
    ogImage = DEFAULT_OG_IMAGE,
  }: {
    /** Omit for the homepage, which uses the site name alone. */
    title?: string;
    description?: string;
    /** Route path beginning with "/". */
    path: string;
    /** false = noindex, and the page must also stay out of sitemap.xml. */
    index?: boolean;
    /** Route of the page's own opengraph-image, e.g. "/about/opengraph-image". */
    ogImage?: string;
  },
): Metadata {
  const ogTitle = title ? `${title} — ${site.name}` : site.name;
  const image = {
    url: ogImage,
    width: 1200,
    height: 630,
    type: "image/png",
    // The default card shows the site line, not this page's title.
    alt: ogImage === DEFAULT_OG_IMAGE ? `${site.name} — ${site.description}` : ogTitle,
  };
  return {
    ...(title ? { title } : { title: { absolute: site.name } }),
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName: site.name,
      locale: "en_US",
      url: path,
      title: ogTitle,
      description,
      images: [image],
    },
    twitter: {
      card: "summary_large_image",
      title: ogTitle,
      description,
      images: [image],
    },
    ...(index ? {} : { robots: { index: false, follow: true } }),
  };
}
